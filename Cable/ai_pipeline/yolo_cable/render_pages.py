def render_one(cable_dir, out_dir):
    pdf = os.path.join(BASE, cable_dir, "Cable.pdf")
    if not os.path.exists(pdf):
        print(f"SKIP (no pdf): {cable_dir}")
        return
    doc = fitz.open(pdf)
    page = doc[0]
    rect = page.rect
    zoom = LONG_SIDE_PX / max(rect.width, rect.height)
    pix = page.get_pixmap(matrix=fitz.Matrix(zoom, zoom))
    name = cable_dir.split("_")[0]
    out = os.path.join(out_dir, f"{name}.png")
    pix.save(out)
    print(f"-> {out}  ({pix.width}x{pix.height})")


def main():
    os.makedirs(OUT, exist_ok=True)
    for c in CABLES:
        render_one(c, OUT)
    print(f"\n총 {len(CABLES)}개 시도, 결과: {OUT}")


if __name__ == "__main__":
    main()
